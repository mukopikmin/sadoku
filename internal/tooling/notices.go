package tooling

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type notice struct{ Name, Version, License, Source, LicenseText string }

func licenseText(dir string) (string, error) {
	for _, name := range []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md", "license.txt", "COPYING", "COPYING.md", "COPYING.txt"} {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err == nil {
			return string(data), nil
		}
		if !os.IsNotExist(err) {
			return "", err
		}
	}
	return "", nil
}
func npmNotices(lockPath, modules string) ([]notice, error) {
	var lock struct {
		Packages map[string]struct{ Version, License, Resolved string }
	}
	data, err := os.ReadFile(lockPath)
	if err != nil {
		return nil, err
	}
	if err = json.Unmarshal(data, &lock); err != nil {
		return nil, err
	}
	var notices []notice
	for path, meta := range lock.Packages {
		if !strings.HasPrefix(path, "node_modules/") || meta.Version == "" || meta.License == "" {
			continue
		}
		name := strings.TrimPrefix(path, "node_modules/")
		dir := filepath.Join(modules, filepath.FromSlash(name))
		var pkg struct{ Repository json.RawMessage }
		source := meta.Resolved
		if source == "" {
			source = lockPath
		}
		data, err := os.ReadFile(filepath.Join(dir, "package.json"))
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		if err == nil {
			if err = json.Unmarshal(data, &pkg); err != nil {
				return nil, err
			}
			var repo string
			var object struct{ URL string }
			if json.Unmarshal(pkg.Repository, &repo) == nil && repo != "" {
				if !strings.Contains(repo, "://") {
					repo = "https://github.com/" + repo
				}
				source = repo
			} else if json.Unmarshal(pkg.Repository, &object) == nil && object.URL != "" {
				source = object.URL
			}
		}
		text, err := licenseText(dir)
		if err != nil {
			return nil, err
		}
		notices = append(notices, notice{name, meta.Version, meta.License, source, text})
	}
	return notices, nil
}
func goNotices() ([]notice, error) {
	modules, err := required(execute("go", "list", "-deps", "-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}", "./cmd/sadoku"), "List Go dependencies")
	if err != nil {
		return nil, err
	}
	var notices []notice
	for _, line := range strings.Split(modules, "\n") {
		fields := strings.Split(line, "\t")
		if len(fields) != 3 || fields[1] == "" || fields[2] == "" {
			continue
		}
		text, err := licenseText(fields[2])
		if err != nil {
			return nil, err
		}
		if text == "" {
			return nil, fmt.Errorf("missing Go module license: %s", fields[0])
		}
		license := "BSD-3-Clause"
		if strings.Contains(text, "Apache License") {
			license = "Apache-2.0"
		} else if strings.Contains(text, "MIT License") {
			license = "MIT"
		}
		notices = append(notices, notice{fields[0], fields[1], license, "https://" + fields[0], text})
	}
	root, err := required(execute("go", "env", "GOROOT"), "Read GOROOT")
	if err != nil {
		return nil, err
	}
	version, err := required(execute("go", "env", "GOVERSION"), "Read Go version")
	if err != nil {
		return nil, err
	}
	text, err := os.ReadFile(filepath.Join(root, "LICENSE"))
	if err != nil {
		return nil, err
	}
	notices = append(notices, notice{"Go runtime", version, "BSD-3-Clause", "https://go.dev", string(text)}, notice{"SQLite", "3.51.1", "Public Domain", "https://sqlite.org/copyright.html", ""})
	return notices, nil
}
func renderNotices(notices []notice) string {
	unique := map[string]notice{}
	for _, n := range notices {
		unique[n.Name+"@"+n.Version] = n
	}
	sorted := make([]notice, 0, len(unique))
	for _, n := range unique {
		sorted = append(sorted, n)
	}
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].Name == sorted[j].Name {
			return sorted[i].Version < sorted[j].Version
		}
		return sorted[i].Name < sorted[j].Name
	})
	var out strings.Builder
	out.WriteString("# Third Party Notices\n\nThis file is generated by `go run ./cmd/sadoku-tools notices`.\n\nThe sadoku release archives include a Go binary and bundled JavaScript assets.\nThe following third-party components are included directly or\nthrough bundled dependencies.\n\n## Summary\n\n| Package | Version | License | Source |\n| --- | --- | --- | --- |\n")
	for _, n := range sorted {
		fmt.Fprintf(&out, "| %s | %s | %s | %s |\n", n.Name, n.Version, n.License, n.Source)
	}
	out.WriteString("\n## License Texts\n")
	for _, n := range sorted {
		if n.LicenseText != "" {
			fmt.Fprintf(&out, "\n## %s %s\n\nLicense: %s\n\n```text\n%s\n```\n", n.Name, n.Version, n.License, strings.TrimSpace(strings.ReplaceAll(n.LicenseText, "\r\n", "\n")))
		}
	}
	return out.String()
}
func generateNotices(output string) error {
	goDeps, err := goNotices()
	if err != nil {
		return err
	}
	npmDeps, err := npmNotices("src/preview/package-lock.json", "src/preview/node_modules")
	if err != nil {
		return err
	}
	return atomicWrite(output, []byte(renderNotices(append(goDeps, npmDeps...))), 0644)
}
